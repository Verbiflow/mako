/**
 * Marks by *harness* — the tool a session belongs to, as distinct from the
 * model provider a message was priced by. Each harness wears its own mark:
 * Codex's prompt-in-a-cloud, Claude Code's glyph, Cursor's cube, Grok's
 * slashed ring.
 */
const HARNESS_MARKS = {
  codex: { mark: Codex, tint: "currentColor" },
  claude: { mark: ClaudeCode, tint: "#D97757" },
  cursor: { mark: Cursor, tint: "currentColor" },
  grok: { mark: Grok, tint: "currentColor" },
  devin: { mark: Devin, tint: "#4E8DF6" },
  opencode: { mark: OpenCode, tint: "currentColor" },
}

/** A harness's mark, sized by the caller. Falls back to initials. */
export function HarnessIcon({
  harness,
  className,
  tinted = true,
}: {
  harness: string
  className?: string
  tinted?: boolean
}) {
  const key = harness.toLowerCase()
  const found = Object.entries(HARNESS_MARKS).find(([id]) => id === key)?.[1]
  if (!found) {
    return (
      <span
        className={cn(
          "inline-flex shrink-0 items-center justify-center rounded-[3px] bg-foreground/10",
          "text-[7px] font-bold tracking-tight text-muted-foreground uppercase",
          className
        )}
        aria-hidden
      >
        {harness.slice(0, 2)}
      </span>
    )
  }
  const Mark = found.mark
  return (
    <Mark
      className={cn("shrink-0", className)}
      style={tinted && found.tint !== "currentColor" ? { color: found.tint } : undefined}
      aria-hidden
    />
  )
}

/**
 * Renders a provider's mark, falling back to its initials — which still reads
 * as identity, where a wrench would read as "unknown".
 */
export function ProviderIcon({
  provider,
  className,
  tinted = true,
}: {
  provider: string
  className?: string
  /** Off inside a coloured surface, where the brand tint would clash. */
  tinted?: boolean
}) {
  const key = provider.toLowerCase()
  const fallbackKey = key.split(/[-/]/)[0]
  const found = Object.entries(MARKS).find(([id]) => id === key)?.[1]
    ?? Object.entries(MARKS).find(([id]) => id === fallbackKey)?.[1]

  if (!found) {
    return (
      <span
        className={cn(
          "inline-flex shrink-0 items-center justify-center rounded-[3px] bg-foreground/10",
          "text-[7px] font-bold tracking-tight text-muted-foreground uppercase",
          className
        )}
        aria-hidden
      >
        {provider.slice(0, 2)}
      </span>
    )
  }

  const Mark = found.mark
  return (
    <Mark
      className={cn("shrink-0", className)}
      style={tinted && found.tint !== "currentColor" ? { color: found.tint } : undefined}
      aria-hidden
    />
  )
}
