import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { LATEST_PROTOCOL_VERSION } from "@modelcontextprotocol/sdk/types.js"
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js"
import { createControlMcpServer } from "@mako/control-runtime/mcp"

/**
 * What an agent's `computer` server says of itself and lists as its tools, written from the server itself
 * (`createControlMcpServer`, built from `packages/control-runtime`): the host answers an agent's handshake and
 * `tools/list` from this, and loads Local Control's server for the first tool call (`tools/conversation-mcp.ts`).
 *
 *   node scripts/computer-manifest.mjs           writes packages/host/src/tools/computer-manifest.ts
 *   node scripts/computer-manifest.mjs --check   fails when that file isn't what the server says now
 */
export const COMPUTER_MANIFEST_FILE = join(import.meta.dirname, "..", "packages", "host", "src", "tools", "computer-manifest.ts")

/** The live server's own answers, asked as an agent asks them and kept as it sent them: no client reads them first. */
export async function liveComputerManifest() {
  const server = createControlMcpServer(async () => {
    throw new Error("A server asked only what it lists calls nothing")
  })
  const [agent, far] = InMemoryTransport.createLinkedPair()
  const waiting = []
  agent.onmessage = (message) => waiting.shift()?.(message)
  await server.connect(far)
  await agent.start()
  const ask = async (message) => {
    const answered = new Promise((resolve) => waiting.push(resolve))
    await agent.send(message)
    return (await answered).result
  }
  const hello = await ask({ jsonrpc: "2.0", id: 1, method: "initialize", params: { protocolVersion: LATEST_PROTOCOL_VERSION, capabilities: {}, clientInfo: { name: "mako-manifest", version: "1.0.0" } } })
  await agent.send({ jsonrpc: "2.0", method: "notifications/initialized" })
  const listed = await ask({ jsonrpc: "2.0", id: 2, method: "tools/list" })
  await server.close()
  return { server: hello.serverInfo, capabilities: hello.capabilities, instructions: hello.instructions ?? null, tools: listed.tools }
}

export function computerManifestText(manifest) {
  return `/**
 * Generated by scripts/computer-manifest.mjs from Local Control's server (\`createControlMcpServer\`); \`test:computer-manifest\`
 * fails when it differs. What an agent's \`computer\` server says of itself and lists, which the host answers without
 * loading that server.
 */
import type { Implementation, ServerCapabilities, Tool } from "@modelcontextprotocol/sdk/types.js"

/** What the \`computer\` server answers an agent's \`initialize\` and \`tools/list\` with. */
export interface ComputerManifest {
  server: Implementation
  capabilities: ServerCapabilities
  instructions: string | null
  tools: Tool[]
}

export const COMPUTER_MANIFEST: ComputerManifest = ${JSON.stringify(manifest, null, 2)}
`
}

if (process.argv[1] && process.argv[1].endsWith("computer-manifest.mjs")) {
  const text = computerManifestText(await liveComputerManifest())
  if (process.argv.includes("--check")) {
    let current = ""
    try {
      current = readFileSync(COMPUTER_MANIFEST_FILE, "utf8")
    } catch {}
    if (current !== text) {
      console.error("computer manifest: packages/host/src/tools/computer-manifest.ts isn't what Local Control's server lists now; run node scripts/computer-manifest.mjs")
      process.exit(1)
    }
    console.log("computer manifest: as Local Control's server lists")
  } else writeFileSync(COMPUTER_MANIFEST_FILE, text)
}
