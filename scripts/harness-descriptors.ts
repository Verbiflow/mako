import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { harnessLabel } from "@mako/host/harnesses/harness-descriptors"
import type { ProviderHost } from "@mako/host/harnesses/host"
import { createHarnessHost, detachedHarnessContext } from "@mako/host/harnesses/harness-host"
import { NativeStores } from "@mako/sessions/read-only-sqlite"

const nativeStores = new NativeStores(false)

/**
 * Writes `src/dev/harness-descriptors.ts`: what the host tells the renderer
 * about each harness that holds on any Mac, for the dev mock and the checks
 * that run without a host; and `src/dev/harness-faces.ts`, each harness's
 * name and mark alone, for what draws a list before anything else (the web
 * client's first screen). `--check` fails when either is behind the harness
 * definitions.
 *
 *   npm run harness:descriptors [-- --check]
 */

export const GENERATED_PATH = join(import.meta.dirname, "..", "src", "dev", "harness-descriptors.ts")
export const FACES_PATH = join(import.meta.dirname, "..", "src", "dev", "harness-faces.ts")

export function renderHarnessDescriptors(host: ProviderHost): string {
  const descriptors = host.harnesses.list().map(({ provider, presentation, capabilities, usage, artifacts, features, unique }) => ({
    provider,
    displayName: harnessLabel(host, provider),
    presentation,
    defaults: host.profiles.get(provider)?.defaults,
    resumable: host.nativeRunners.get(provider) !== undefined,
    capabilities,
    usage,
    artifacts,
    features,
    unique,
  }))
  return [
    "// Generated by `npm run harness:descriptors` from the harness definitions. Do not edit.",
    'import type { HarnessDescriptor } from "@/lib/types"',
    "",
    "/** Every harness in Mako's order, as the host describes it on any Mac. */",
    `export const harnessDescriptors: Pick<HarnessDescriptor, "provider" | "displayName" | "presentation" | "defaults" | "resumable" | "capabilities" | "usage" | "artifacts" | "features" | "unique">[] = ${JSON.stringify(descriptors, null, 2)}`,
    "",
  ].join("\n")
}

/** Each harness's name and mark, in Mako's order: all a list needs to draw a row's harness. */
export function renderHarnessFaces(host: ProviderHost): string {
  const faces = host.harnesses.list().map(({ provider, presentation }) => ({ provider, displayName: harnessLabel(host, provider), presentation }))
  return [
    "// Generated by `npm run harness:descriptors` from the harness definitions. Do not edit.",
    'import type { HarnessDescriptor } from "@/lib/types"',
    "",
    "/** Every harness in Mako's order, its name and mark: what a list draws before the rest of `harnessDescriptors`. */",
    `export const harnessFaces: Pick<HarnessDescriptor, "provider" | "displayName" | "presentation">[] = ${JSON.stringify(faces, null, 2)}`,
    "",
  ].join("\n")
}

if (import.meta.filename === process.argv[1]) {
  const host = createHarnessHost(detachedHarnessContext(nativeStores))
  const files = [
    { path: GENERATED_PATH, rendered: renderHarnessDescriptors(host) },
    { path: FACES_PATH, rendered: renderHarnessFaces(host) },
  ]
  if (process.argv.includes("--check")) {
    for (const file of files)
      if (readFileSync(file.path, "utf8") !== file.rendered) {
        console.error(`${file.path} is behind the harness definitions. Run: npm run harness:descriptors`)
        process.exit(1)
      }
    console.log("Harness descriptors: the dev snapshots match the definitions")
  } else {
    for (const file of files) {
      writeFileSync(file.path, file.rendered)
      console.log(`Wrote ${file.path}`)
    }
  }
}
