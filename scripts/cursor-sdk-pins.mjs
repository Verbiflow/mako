import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { CURSOR_SDK_PATCHES, folderFiles, patchFile } from "./patch-cursor-sdk.mjs"

/**
 * What a host made without Cursor checks the SDK Settings installs against (`harnesses/cursor/sdk/installed.ts`),
 * written from what this checkout pins and holds: each package's tarball hash from package-lock.json, and the hash of
 * each file Mako's patches rewrite, as patched here. The host carries them as a module, not the lockfile.
 *
 *   node scripts/cursor-sdk-pins.mjs           writes packages/host/src/harnesses/cursor/sdk/pins.ts
 *   node scripts/cursor-sdk-pins.mjs --check   fails when that file isn't what this checkout pins
 */
const root = join(import.meta.dirname, "..")
const target = join(root, "packages", "host", "src", "harnesses", "cursor", "sdk", "pins.ts")
const locked = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8")).packages
const sdk = locked["node_modules/@cursor/sdk"]
if (!sdk) throw new Error("package-lock.json has no @cursor/sdk")
const names = ["@cursor/sdk", ...Object.keys(sdk.optionalDependencies ?? {}).sort()]
const tarballs = Object.fromEntries(names.map((name) => {
  const entry = locked[`node_modules/${name}`]
  if (!entry || entry.version !== sdk.version) throw new Error(`package-lock.json has no ${name} ${sdk.version}`)
  if (!/^sha512-[A-Za-z0-9+/]+=*$/.test(entry.integrity)) throw new Error(`${name}'s integrity in package-lock.json isn't one sha512`)
  return [name, entry.integrity]
}))
const installed = join(root, "node_modules", "@cursor", "sdk")
const read = (file) => readFileSync(join(installed, file), "utf8")
const held = JSON.parse(read("package.json")).version
if (held !== sdk.version) throw new Error(`node_modules holds @cursor/sdk ${held}, the lockfile ${sdk.version}: npm ci first`)
const files = folderFiles(installed)
const patched = Object.fromEntries([...new Set(CURSOR_SDK_PATCHES.map((patch) => {
  const file = patchFile(read, files, patch, true)
  if (!file) throw new Error(`node_modules' @cursor/sdk lacks Mako's ${patch.change} (${patch.build}) patch: run scripts/patch-cursor-sdk.mjs first`)
  return file
}))].sort().map((file) => [file, createHash("sha256").update(readFileSync(join(installed, file))).digest("hex")]))

const text = `/**
 * Generated by scripts/cursor-sdk-pins.mjs from package-lock.json and the patched SDK in node_modules; \`lint:rules\`
 * fails when it differs. What an SDK installed from Settings must be (\`installed.ts\`): each package's tarball by the
 * hash the lockfile pins, and each file Mako's patches rewrite by its hash once patched.
 */
export const CURSOR_SDK_PINS = ${JSON.stringify({ version: sdk.version, tarballs, patched }, null, 2)} as const
`
if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(target, "utf8")
  } catch {}
  if (current !== text) {
    console.error("cursor sdk pins: packages/host/src/harnesses/cursor/sdk/pins.ts isn't what package-lock.json and the patched SDK pin; run node scripts/cursor-sdk-pins.mjs")
    process.exit(1)
  }
  console.log(`cursor sdk pins: @cursor/sdk ${sdk.version}, ${names.length} tarballs and ${Object.keys(patched).length} patched files as pinned`)
} else writeFileSync(target, text)
